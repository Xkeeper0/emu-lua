

keycounterart		= {
	0x0E, 0x0E, 0x1B, 0x1B, 0x11, 0x11, 0x1B, 0x1B, 
	0x3E, 0x3E, 0x60, 0x60, 0xF0, 0xF0, 0xA0, 0xA0, 
	0x00, 0x00, 0x00, 0x00, 0x22, 0x22, 0x14, 0x14, 
	0x08, 0x08, 0x14, 0x14, 0x22, 0x22, 0x00, 0x00,
	}

function drawkeycounter()
	for i = 0, 0x1F do
		mem.byte[0x8C80 + i] = keycounterart[i + 1]
	end
end



	-- Key counter code
	-- FFF7 = Submap (better)
	-- DB60 = Submap too (?)
	-- DB5F = Mode (?)
function draw_dungeon_keys()
	local submap		= mem.byte[c.hMapId]
	local mapmode		= mem.byte[c.wSpawnIsIndoor]

	if mapmode == 1 and (submap <= 0x07 or submap == 0xFF) then
		if mem.byte[0x8C80] == 0xFF then
			drawkeycounter()
		end

		mem.byte[0x9C0A]	= 0xC8
		mem.byte[0x9C0B]	= 0xC9
		mem.byte[0x9C0C]	= 0xB0 + mem.byte[c.wSmallKeysCount]
	end
end